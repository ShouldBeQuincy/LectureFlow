//go:build !windows && !linux && !darwin

package main

import (
	"os"
	"time"
)

// lastChange: only the modification time is known here.
func lastChange(path string) (time.Time, error) {
	fi, err := os.Stat(path)
	if err != nil {
		return time.Time{}, err
	}
	return fi.ModTime(), nil
}
